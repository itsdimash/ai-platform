def one_layout(layout: str) -> dict:
    """Колода из титульного слайда и одного слайда нужного layout'а."""
    base = {"title": "Тест", "theme": "graphite", "summary": "s"}
    slide = {"layout": layout, "title": f"Слайд {layout}", "notes": "Заметки докладчика."}
    extra = {
        "section": {"subtitle": "Подзаголовок"},
        "bullets": {"bullets": ["Один", "Два", "Три"]},
        "cards": {"cards": [{"title": "А", "text": "Текст А"}, {"title": "Б", "text": "Текст Б"}]},
        "stat": {
            "stats": [{"value": "42%", "label": "рост"}, {"value": "7 дней", "label": "срок"}]
        },
        "two_column": {"left": ["л1", "л2"], "right": ["п1", "п2"]},
        "comparison": {
            "cards": [
                {"title": "До", "text": "медленно; дорого"},
                {"title": "После", "text": "быстро; дёшево"},
            ]
        },
        "timeline": {
            "steps": [
                {"title": "Старт", "text": "Начало"},
                {"title": "Финиш", "text": "Конец"},
                {"title": "Итог", "text": "Отчёт"},
            ]
        },
        "image": {"bullets": ["Подпись к картинке"], "image_prompt": "A lighthouse at sunset"},
        "table": {"table": {"headers": ["А", "Б"], "rows": [["1", "2"], ["3", "4"]]}},
        "chart": {
            "chart": {
                "type": "line",
                "categories": ["a", "b", "c"],
                "series": [{"name": "S", "values": [1, 3, 2]}],
            }
        },
        "quote": {"quote": {"text": "Короткая цитата.", "author": "Автор"}},
        "closing": {"bullets": ["Шаг 1", "Шаг 2"]},
    }[layout]
    slides = [{**slide, **extra}]
    if layout == "section":  # разделы допускаются только в колоде из >= 12 слайдов
        filler = {
            "layout": "bullets",
            "title": "Заполнитель",
            "bullets": ["Раз", "Два"],
            "notes": "n",
        }
        slides = [filler] * 10 + slides
    return {**base, "slides": slides}


